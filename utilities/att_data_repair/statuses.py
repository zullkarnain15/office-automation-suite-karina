"""Central status, change, anomaly, and fatal codes."""

from __future__ import annotations

from enum import StrEnum


class FinalStatus(StrEnum):
    VALID_UNCHANGED = "VALID_UNCHANGED"
    REPAIRED = "REPAIRED"


class ChangeCode(StrEnum):
    NIK_LEADING_TWO_RESTORED = "NIK_LEADING_TWO_RESTORED"
    NIK_MISSING_ZERO_RESTORED = "NIK_MISSING_ZERO_RESTORED"
    NIK_EXTRA_LEADING_TWO_REMOVED = "NIK_EXTRA_LEADING_TWO_REMOVED"
    NIK_LEADING_TWO_REPLACED = "NIK_LEADING_TWO_REPLACED"
    DATE_YEAR_ALIGNED_TO_CURRENT_YEAR = "DATE_YEAR_ALIGNED_TO_CURRENT_YEAR"
    DATE_OUT_ALIGNED_TO_DATE_IN = "DATE_OUT_ALIGNED_TO_DATE_IN"
    TIME_FORMAT_NORMALIZED = "TIME_FORMAT_NORMALIZED"
    MIDNIGHT_TIME_IN_DEFAULTED = "MIDNIGHT_TIME_IN_DEFAULTED"
    MIDNIGHT_TIME_OUT_DEFAULTED = "MIDNIGHT_TIME_OUT_DEFAULTED"
    SATURDAY_MISSING_OUT_DEFAULTED = "SATURDAY_MISSING_OUT_DEFAULTED"
    TIME_IN_OUT_SWAPPED = "TIME_IN_OUT_SWAPPED"
    PARTIAL_TIME_REPAIRED = "PARTIAL_TIME_REPAIRED"
    DEFAULT_TIME_APPLIED = "DEFAULT_TIME_APPLIED"
    MINIMUM_DURATION_APPLIED = "MINIMUM_DURATION_APPLIED"


class AnomalyCode(StrEnum):
    INVALID_NIK = "INVALID_NIK"
    INVALID_DATE = "INVALID_DATE"
    OUTSIDE_REPORT_PERIOD = "OUTSIDE_REPORT_PERIOD"
    INVALID_WORKFLOW = "INVALID_WORKFLOW"
    DUPLICATE_RECORD = "DUPLICATE_RECORD"
    SUNDAY_NOT_MONTH_END = "SUNDAY_NOT_MONTH_END"


class FatalCode(StrEnum):
    MISSING_REQUIRED_SHEET = "MISSING_REQUIRED_SHEET"
    MISSING_REQUIRED_COLUMN = "MISSING_REQUIRED_COLUMN"
    INVALID_SOURCE_WORKBOOK = "INVALID_SOURCE_WORKBOOK"
    INVALID_REQUEST = "INVALID_REQUEST"


class JobStatus(StrEnum):
    SUCCESS = "SUCCESS"
    PARTIAL_SUCCESS = "PARTIAL_SUCCESS"
    NO_VALID_RECORDS = "NO_VALID_RECORDS"
    FAILED = "FAILED"
